// Pure helpers: boilerplate stripping, workspace detection, search terms.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { cleanMessage, makeTitle, workspaceFromCwd, queryTerms, snippet } from '../lib/text.js'

test('workspaceFromCwd: the project folder under a POSIX home is the workspace', () => {
  assert.equal(workspaceFromCwd('/Users/chang/myproject'), 'myproject')
  assert.equal(workspaceFromCwd('/home/chang/myproject'), 'myproject')
  assert.equal(workspaceFromCwd('/Users/chang/code/proj'), 'proj')
})

test('workspaceFromCwd: a home folder itself is not a workspace', () => {
  assert.equal(workspaceFromCwd('/Users/chang'), null)
  assert.equal(workspaceFromCwd('/home/chang/'), null)
  assert.equal(workspaceFromCwd('C:\\Users\\Chang'), null)
  assert.equal(workspaceFromCwd('/root'), null)
  assert.equal(workspaceFromCwd('C:\\'), null)
  assert.equal(workspaceFromCwd(''), null)
})

test('workspaceFromCwd: Windows paths, including folders on other drives', () => {
  assert.equal(workspaceFromCwd('C:\\Users\\Chang\\empirehacks-2026'), 'empirehacks-2026')
  assert.equal(workspaceFromCwd('D:\\work\\proj'), 'proj')
  assert.equal(workspaceFromCwd('D:\\proj'), 'proj')
})

test('workspaceFromCwd: Cowork VM mounts', () => {
  assert.equal(workspaceFromCwd('/sessions/brave-owl/mnt/thesis/chapter1'), 'thesis')
  assert.equal(workspaceFromCwd('/sessions/brave-owl/mnt/outputs'), null)
  assert.equal(workspaceFromCwd('/sessions/brave-owl'), null)
})

test('cleanMessage drops injected context and pure boilerplate', () => {
  assert.equal(cleanMessage('<system-reminder>be nice</system-reminder>\nfix the login bug'), 'fix the login bug')
  assert.equal(cleanMessage('<environment_context><cwd>/x</cwd></environment_context>'), '')
  assert.equal(cleanMessage('Caveat: The messages below were generated by the user'), '')
  assert.equal(cleanMessage('<scheduled-task name="daily digest">run it</scheduled-task>'), '定时任务: daily digest')
  assert.equal(cleanMessage('# AGENTS.md instructions for repo\n...\n## My request for Codex:\nadd tests'), 'add tests')
})

test('makeTitle collapses whitespace and truncates', () => {
  assert.equal(makeTitle('  hello \n world  '), 'hello world')
  assert.equal(makeTitle('x'.repeat(70)), 'x'.repeat(60) + '…')
  assert.equal(makeTitle(''), '')
})

test('queryTerms: latin words, short CJK runs whole, long CJK runs as bigrams', () => {
  assert.deepEqual(queryTerms('FlClash tailscale a'), ['flclash', 'tailscale'])
  assert.deepEqual(queryTerms('甲骨文'), ['甲骨文'])
  assert.deepEqual(queryTerms('自动驾驶'), ['自动', '动驾', '驾驶'])
  assert.deepEqual(queryTerms('甲骨文 ARM 抢占').sort(), ['arm', '抢占', '甲骨文'].sort())
})

test('snippet centres on the first hit', () => {
  const text = 'a'.repeat(500) + ' needle ' + 'b'.repeat(500)
  const s = snippet(text, ['needle'], 100)
  assert.ok(s.includes('needle'))
  assert.ok(s.startsWith('…') && s.endsWith('…'))
  assert.equal(snippet('short text', ['zzz']), 'short text')
})
